import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";

const API = "http://127.0.0.1:8000";

async function readResponse(response) {
  const body = await response.text();

  if (!response.ok) {
    let message = body || `Request failed (${response.status})`;

    try {
      const parsed = JSON.parse(body);
      message = parsed.detail || parsed.message || message;
    } catch {
      // Keep the response body if it isn't JSON.
    }

    throw new Error(message);
  }

  return body ? JSON.parse(body) : null;
}

function getStoredUser() {
  try {
    return JSON.parse(localStorage.getItem("user") || "null");
  } catch {
    localStorage.removeItem("user");
    return null;
  }
}

function StudentDashboard() {
  const navigate = useNavigate();
  const [user, setUser] = useState(() => getStoredUser());
  const profile = user;
  const [form, setForm] = useState({
    first_name: user?.first_name ?? "",
    last_name: user?.last_name ?? "",
    email: user?.email ?? "",
    phone: user?.phone ?? "",
    current_password: "",
    new_password: "",
  });
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  useEffect(() => {
    if (!user || user.role !== "student") {
      navigate("/login", { replace: true });
      return;
    }

  }, [navigate, user]);

  function handleLogout() {
    localStorage.removeItem("user");
    setUser(null);
    navigate("/login", { replace: true });
  }

  async function saveProfile(event) {
    event.preventDefault();
    setSaving(true);
    setError("");
    setNotice("");

    try {
      const response = await fetch(`${API}/students/profile`, {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          current_username: user.username,
          current_password: form.current_password,
          first_name: form.first_name.trim(),
          last_name: form.last_name.trim(),
          email: form.email.trim() || null,
          phone: form.phone.trim() || null,
          new_password: form.new_password || null,
        }),
      });
      const data = await readResponse(response);

      localStorage.removeItem("user");
      navigate("/login", {
        replace: true,
        state: {
          username: data.username,
          notice: "Your profile was updated. Sign in again to continue.",
        },
      });
    } catch (saveError) {
      setError(saveError.message || "Unable to update your profile.");
    } finally {
      setSaving(false);
    }
  }

  if (!user || user.role !== "student") {
    return null;
  }

  return (
    <div className="min-h-screen bg-slate-100">
      <header className="border-b-4 border-red-600 bg-white shadow-sm">
        <div className="mx-auto flex max-w-5xl flex-wrap items-center justify-between gap-4 px-6 py-4">
          <div>
            <p className="text-sm font-bold uppercase tracking-widest text-red-600">
              Dallas College Library
            </p>
            <h1 className="text-2xl font-black text-blue-950">
              Student Dashboard
            </h1>
          </div>
          <div className="flex gap-3">
            <button
              type="button"
              onClick={() => navigate("/ProductCatalog")}
              className="rounded-lg bg-blue-900 px-4 py-2 text-sm font-bold text-white hover:bg-blue-800"
            >
              Browse catalog
            </button>
            <button
              type="button"
              onClick={handleLogout}
              className="rounded-lg border border-red-200 px-4 py-2 text-sm font-bold text-red-700 hover:bg-red-50"
            >
              Sign out
            </button>
          </div>
        </div>
      </header>

      <main className="mx-auto max-w-5xl px-6 py-8">
        <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm sm:p-8">
          <div>
            <h2 className="text-xl font-black text-slate-900">
              Personal information
            </h2>
            <p className="mt-1 text-sm text-slate-600">
              Update your details below. You can clear email or phone by
              leaving the field blank. Your Student ID is generated by the
              system and cannot be changed.
            </p>
          </div>

          {error && (
            <p
              role="alert"
              className="mt-5 rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700"
            >
              {error}
            </p>
          )}
          {notice && (
            <p
              role="status"
              className="mt-5 rounded-lg border border-green-200 bg-green-50 px-4 py-3 text-sm text-green-800"
            >
              {notice}
            </p>
          )}

          {profile ? (
            <form onSubmit={saveProfile} className="mt-6 space-y-5">
              <div className="grid gap-5 sm:grid-cols-2">
                <label className="block text-sm font-bold text-slate-700">
                  First name
                  <input
                    required
                    maxLength={100}
                    autoComplete="given-name"
                    value={form.first_name}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        first_name: event.target.value,
                      }))
                    }
                    className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 font-normal outline-none focus:border-blue-700 focus:ring-2 focus:ring-blue-100"
                  />
                </label>

                <label className="block text-sm font-bold text-slate-700">
                  Last name
                  <input
                    required
                    maxLength={100}
                    autoComplete="family-name"
                    value={form.last_name}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        last_name: event.target.value,
                      }))
                    }
                    className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 font-normal outline-none focus:border-blue-700 focus:ring-2 focus:ring-blue-100"
                  />
                </label>

                <label className="block text-sm font-bold text-slate-700">
                  Email <span className="font-normal text-slate-400">(optional)</span>
                  <input
                    type="email"
                    maxLength={254}
                    autoComplete="email"
                    value={form.email}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        email: event.target.value,
                      }))
                    }
                    className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 font-normal outline-none focus:border-blue-700 focus:ring-2 focus:ring-blue-100"
                  />
                </label>

                <label className="block text-sm font-bold text-slate-700">
                  Phone <span className="font-normal text-slate-400">(optional)</span>
                  <input
                    type="tel"
                    maxLength={30}
                    autoComplete="tel"
                    value={form.phone}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        phone: event.target.value,
                      }))
                    }
                    className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 font-normal outline-none focus:border-blue-700 focus:ring-2 focus:ring-blue-100"
                  />
                </label>

                <label className="block text-sm font-bold text-slate-700">
                  Username
                  <input
                    readOnly
                    value={profile.username}
                    className="mt-1 w-full rounded-lg border border-slate-200 bg-slate-50 px-3 py-2 font-normal text-slate-500"
                  />
                </label>

                <label className="block text-sm font-bold text-slate-700">
                  Student ID
                  <input
                    readOnly
                    value={profile.student_id ?? ""}
                    className="mt-1 w-full rounded-lg border border-slate-200 bg-slate-50 px-3 py-2 font-normal text-slate-500"
                  />
                </label>
              </div>

              <div className="grid gap-5 border-t border-slate-200 pt-5 sm:grid-cols-2">
                <label className="block text-sm font-bold text-slate-700">
                  Current password
                  <input
                    required
                    type="password"
                    autoComplete="current-password"
                    value={form.current_password}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        current_password: event.target.value,
                      }))
                    }
                    className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 font-normal outline-none focus:border-blue-700 focus:ring-2 focus:ring-blue-100"
                  />
                </label>

                <label className="block text-sm font-bold text-slate-700">
                  New password <span className="font-normal text-slate-400">(optional)</span>
                  <input
                    type="password"
                    minLength={8}
                    maxLength={255}
                    autoComplete="new-password"
                    value={form.new_password}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        new_password: event.target.value,
                      }))
                    }
                    className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2 font-normal outline-none focus:border-blue-700 focus:ring-2 focus:ring-blue-100"
                  />
                </label>
              </div>

              <div className="flex justify-end">
                <button
                  type="submit"
                  disabled={saving}
                  className="rounded-lg bg-red-600 px-5 py-3 text-sm font-bold text-white hover:bg-red-700 disabled:cursor-not-allowed disabled:opacity-60"
                >
                  {saving ? "Saving profile…" : "Save changes"}
                </button>
              </div>
            </form>
          ) : (
            <button
              type="button"
              onClick={handleLogout}
              className="mt-5 rounded-lg bg-blue-900 px-4 py-2 text-sm font-bold text-white hover:bg-blue-800"
            >
              Sign in again
            </button>
          )}
        </section>
      </main>
    </div>
  );
}

export default StudentDashboard;
